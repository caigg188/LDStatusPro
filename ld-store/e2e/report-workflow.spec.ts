import { test, expect, signIn } from './fixtures'
test('submits from product detail, receives a receipt and supplements the original case', async ({ page, scenario }, info) => {
  void scenario
  await signIn(page)
  const report: any = { id: 383, target_type: 'product', product_id: 7, product_name: '回归测试物品', report_category_label: '无法使用或交付异常', report_reason: '兑换的卡密无法使用，请核查具体报错', status: 'awaiting_info', admin_note: '请补充具体报错和发生时间', next_step: '补充原记录，不重复举报', revision: 1, created_at: Date.now(), updated_at: Date.now() }
  let submitted: any, supplement: any
  await page.route('**/api/shop/products/7/report', route => { submitted = route.request().postDataJSON(); return route.fulfill({ json: { success: true, reportId: 383, targetType: 'product' } }) })
  await page.route('**/api/shop/reports/product/383', route => route.fulfill({ json: { report, events: [{ public_note: '请补充具体报错和发生时间', created_at: Date.now() }], evidence: [] } }))
  await page.route('**/api/shop/reports/product/383/supplements', route => { supplement = route.request().postDataJSON(); report.status = 'processing'; return route.fulfill({ json: { replayed: false } }) })
  await page.goto('/product/7')
  await page.getByRole('button', { name: '举报', exact: true }).click()
  const modal = page.getByRole('dialog', { name: '反馈物品问题' })
  await expect(modal.getByLabel('问题分类')).toHaveValue('')
  await modal.getByLabel('问题分类').selectOption('delivery_issue')
  await modal.getByLabel('详细说明').fill(report.report_reason)
  await modal.getByRole('button', { name: '提交举报' }).click()
  await expect(modal.getByText('举报已提交', { exact: true })).toBeVisible()
  expect(submitted.submissionToken).toMatch(/^[\w-]{16,}$/)
  await modal.getByRole('link', { name: '查看进度 / 补充证据' }).click()
  await expect(page.getByRole('heading', { name: '举报 #383' })).toBeVisible()
  await page.getByLabel('问题说明或新证据').fill('已经补充卡密报错与具体发生时间')
  await page.getByRole('button', { name: '提交补充说明' }).click()
  await expect(page.getByText('核查中', { exact: true })).toBeVisible()
  expect(supplement.review).toBe(false)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/report-detail-'+info.project.name+'.png', fullPage: true })
})
test('distinguishes loading failure from empty records and preserves pagination on return', async ({ page, scenario }, info) => {
  void scenario
  await signIn(page)
  let failed = true
  await page.route('**/api/shop/reports?*', route => failed ? route.fulfill({ status: 503, json: { success: false, error: { code: 'TEST_READ_FAILED', message: '模拟举报读取失败' } } }) : route.fulfill({ json: { reports: [{ id: 23, target_type: 'comment', status: 'pending', product_id: 7, report_reason: '评论存在事实争议，需要核查', created_at: Date.now() }], stats: { open: 61, awaiting_info: 3, closed: 10 }, pagination: { total: 61, totalPages: 4 } } }))
  await page.route('**/api/shop/reports/comment/23', route => route.fulfill({ json: { report: { id: 23, target_type: 'comment', status: 'pending', product_id: 7, report_reason: '评论存在事实争议，需要核查', created_at: Date.now() }, events: [], evidence: [] } }))
  await page.goto('/user/reports?page=2&type=comment')
  await expect(page.getByRole('alert')).toContainText('模拟举报读取失败')
  await expect(page.getByText('当前筛选下暂无举报记录。')).toHaveCount(0)
  failed = false; await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByText('2 / 4 · 共 61 条')).toBeVisible()
  await page.getByRole('link').filter({ hasText: '评论举报 #23' }).click()
  await page.getByRole('link', { name: '← 返回举报列表' }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(page.getByText('2 / 4 · 共 61 条')).toBeVisible()
  await page.screenshot({ path: 'test-results/report-list-'+info.project.name+'.png', fullPage: true })
})
test('keeps an uncertain submission and retry token, with keyboard focus restored on close', async ({ page, scenario }) => {
  void scenario
  await signIn(page)
  const writes: any[] = []
  await page.route('**/api/shop/products/7/report', route => {
    writes.push(route.request().postDataJSON())
    return writes.length===1 ? route.abort('failed') : route.fulfill({json:{reportId:383,targetType:'product'}})
  })
  await page.goto('/product/7')
  const trigger=page.getByRole('button',{name:'举报',exact:true})
  await trigger.click()
  const modal=page.getByRole('dialog',{name:'反馈物品问题'})
  await expect(modal.getByLabel('问题分类')).toBeFocused()
  await modal.getByLabel('问题分类').selectOption('delivery_issue')
  await modal.getByLabel('详细说明').fill('卡密无法使用，请核查具体报错')
  await modal.getByRole('button',{name:'提交举报'}).click()
  await expect(modal.getByRole('alert')).toBeVisible()
  await expect(modal.getByLabel('详细说明')).toHaveValue('卡密无法使用，请核查具体报错')
  await modal.getByRole('button',{name:'提交举报'}).click()
  await expect(modal.getByText('举报已提交',{exact:true})).toBeVisible()
  expect(writes[0].submissionToken).toBe(writes[1].submissionToken)
  await page.keyboard.press('Escape')
  await expect(modal).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
